# # Анализ динамики численности маргариток
#
# В данном скрипте исследуется изменение численности чёрных и белых маргариток
# в процессе эволюции модели Daisyworld. Строится график зависимости количества
# маргариток от модельного времени.
#
# ## Инициализация проекта и загрузка пакетов

using DrWatson
@quickactivate "project"

using Agents
using DataFrames
using Plots

# ### Подключение модели
#
# Импортируем определение модели Daisyworld из исходного файла.

include(srcdir("daisyworld.jl"))

# ### Настройка визуализации
#
# Для построения графиков используется библиотека CairoMakie,
# обеспечивающая высокое качество отображения.

using CairoMakie

# ## Определение агрегатных функций
#
# Для сбора статистики о популяции маргариток определим две функции,
# которые проверяют принадлежность агента к определённому виду:
# - `black(a)` — возвращает `true`, если маргаритка чёрная
# - `white(a)` — возвращает `true`, если маргаритка белая

black(a) = a.breed == :black
white(a) = a.breed == :white

# ### Агрегатные данные
#
# `adata` определяет, какие данные о агентах будут собираться в процессе
# моделирования. Здесь мы собираем количество чёрных и белых маргариток
# на каждом шаге.

adata = [(black, count), (white, count)]

# ## Запуск модели
#
# Создаём модель с начальной солнечной светимостью 1.0 и запускаем
# симуляцию на 1000 шагов. Результаты сохраняются в два DataFrame:
# - `agent_df` — данные об агентах на каждом шаге
# - `model_df` — данные о модели (не используются в данном скрипте)

model = daisyworld(; solar_luminosity = 1.0)
agent_df, model_df = run!(model, 1000; adata)

# ## Построение графика численности
#
# ### Создание фигуры и осей
#
# Создаём фигуру размером 600×400 пикселей с одной осью,
# где по оси X откладывается время (tick), а по оси Y — количество маргариток.

figure = Figure(size = (600, 400))
ax = figure[1, 1] = Axis(figure,
    xlabel = "tick",
    ylabel = "daisy count"
)

# ### Отображение динамики чёрных маргариток
#
# Строим линию для чёрных маргариток. Цвет линии — чёрный.

blackl = lines!(ax,
    agent_df[!, :time],
    agent_df[!, :count_black],
    color = :black
)

# ### Отображение динамики белых маргариток
#
# Строим линию для белых маргариток. Цвет линии — оранжевый.

whitel = lines!(ax,
    agent_df[!, :time],
    agent_df[!, :count_white],
    color = :orange
)

# ### Добавление легенды
#
# Добавляем легенду, которая идентифицирует линии на графике.
# Легенда размещается справа от основного графика.

Legend(figure[1, 2],
    [blackl, whitel],
    ["black", "white"],
    labelsize = 12
)

# ## Сохранение результата
#
# Сохраняем полученный график в каталог `plots/` с именем `daisy_count.png`.

save(plotsdir("daisy_count.png"), figure)

# ## Интерпретация результатов
#
# На полученном графике можно наблюдать динамику взаимодействия
# двух видов маргариток:
#
# 1. **Начальная фаза** — оба вида присутствуют в равных пропорциях.
# 2. **Конкуренция** — в зависимости от начальных условий и температуры
#    один из видов может получить преимущество.
# 3. **Установление равновесия** — система приходит к стабильному состоянию,
#    где численность маргариток обоих видов стабилизируется.
#
# Особый интерес представляет поведение системы при изменении
# солнечной светимости, что демонстрирует способность биосферы
# к саморегуляции (гипотеза Геи).