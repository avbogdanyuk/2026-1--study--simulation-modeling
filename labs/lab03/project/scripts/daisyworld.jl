# # Визуализация модели Daisyworld
#
# В данном скрипте демонстрируется визуализация модели Daisyworld
# на разных этапах эволюции. Маргаритки отображаются в виде цветов,
# а фон показывает температуру поверхности.
#
# ## Инициализация проекта и загрузка пакетов

using DrWatson
@quickactivate "project"

using Agents
using DataFrames
using Plots

# ### Подключение модели
#
# Импортируем определение модели Daisyworld из исходного файла.

include(srcdir("daisyworld.jl"))

# ### Настройка визуализации
#
# Для отображения используется библиотека CairoMakie,
# которая обеспечивает высокое качество графики.

using CairoMakie

# ## Создание модели
#
# Инициализируем мир с параметрами по умолчанию.

model = daisyworld()

# ### Определение цвета агента
#
# Функция `daisycolor` возвращает цвет маргаритки в зависимости от её вида:
# - чёрные маргаритки будут отображаться одним цветом
# - белые маргаритки — другим

daisycolor(a::Daisy) = a.breed

# ### Параметры отображения
#
# Задаём общие параметры для всех графиков:
# - `agent_color` — функция определения цвета агента
# - `agent_size` — размер маргаритки
# - `agent_marker` — символ для отображения маргаритки (цветок ✿)
# - `heatarray` — массив для тепловой карты (температура)
# - `heatkwargs` — параметры тепловой карты (диапазон от -20 до 60°C)

plotkwargs = (
    agent_color = daisycolor,
    agent_size = 20,
    agent_marker = '✿',
    heatarray = :temperature,
    heatkwargs = (colorrange = (-20, 60),),
)

# ## Визуализация начального состояния
#
# Отображаем мир на шаге 0 (начальное состояние).

plt1, _ = abmplot(model; plotkwargs...)

# ## Визуализация после 5 шагов
#
# Выполняем 5 шагов модели и отображаем результат.

step!(model, 5)
plt2, _ = abmplot(model; heatarray = model.temperature, plotkwargs...)

# ## Визуализация после 40 шагов
#
# Выполняем ещё 40 шагов (всего 45 шагов от начала) и отображаем результат.

step!(model, 40)
plt3, _ = abmplot(model; heatarray = model.temperature, plotkwargs...)

# ## Сохранение результатов
#
# Сохраняем полученные графики в каталог `plots/`.

save(plotsdir("daisy_step001.png"), plt1)
save(plotsdir("daisy_step005.png"), plt2)
save(plotsdir("daisy_step040.png"), plt3)

# ## Интерпретация результатов
#
# На полученных изображениях можно наблюдать:
# 1. **Начальное состояние (step 0)** — маргаритки случайно распределены по полю.
# 2. **После 5 шагов** — начинается локальное изменение температуры вокруг маргариток.
# 3. **После 40 шагов** — формируются кластеры маргариток, температура стабилизируется.
#
# Чёрные маргаритки (поглощают больше света) создают локальные области нагрева,
# белые маргаритки (отражают свет) — области охлаждения. Эта обратная связь
# позволяет системе саморегулироваться в широком диапазоне параметров.